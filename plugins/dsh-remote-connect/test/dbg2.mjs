import fs from 'node:fs/promises'; import os from 'node:os'; import path from 'node:path'; import http from 'node:http';
const tmp = await fs.mkdtemp(path.join(os.tmpdir(),'dbg2-')); const port = 24567;
process.env.DEVICE_LINK_HOME=path.join(tmp,'data'); process.env.DEVICE_LINK_DSH_HOME=path.join(tmp,'dsh');
const { ConfigStore } = await import('../host/config.mjs');
const store = new ConfigStore(); await store.load();
await store.patch({server:{enabled:true,port,bind:'127.0.0.1',discovery:false}});
await store.setPassword('SMOKE-PASSWORD-123'); console.log('cfg ready');
const routes = new Map();
const fakeWeb = { register({path:p,handler}){routes.set(p,handler); return ()=>routes.delete(p)}, get port(){return port} };
const server = http.createServer((req,res)=>{ console.log('REQ',req.method,req.url); const h=routes.get(new URL(req.url,'http://x').pathname); if(!h){res.writeHead(404);return res.end('{}')} h(req,res) });
await new Promise((r)=>{server.on('error',e=>{console.error('LISTEN ERR',e);process.exit(2)}); server.listen(port,'127.0.0.1',r)}); console.log('fake up');
const disposers=[]; const ctx={get:(n)=>n==='webServer'?fakeWeb:null,effect:(fn)=>{const d=fn(); if(typeof d==='function')disposers.push(d)}};
console.log('importing plugin...');
const plugin = await import('../index.js'); console.log('imported');
plugin.apply(ctx); console.log('applied, routes',routes.size);
const res = await fetch(`http://127.0.0.1:${port}/dsh-remote-connect-api/status`); console.log('fetch status',res.status);
const j = await res.json(); console.log('json ok',j.ok,'server',j.data?.server?.running);
for(const d of disposers)d(); await new Promise(r=>setTimeout(r,300)); server.close(); await fs.rm(tmp,{recursive:true,force:true}); process.exit(0);
