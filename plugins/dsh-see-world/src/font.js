/** 字形 = 7 行 × 5 列，1 = 亮。 */
const TABLE = GLYPHS.map((g) => g.split(',').map((row) => row.split('').map((c) => c === '1')));

function glyphOf(ch) {
  const code = ch.codePointAt(0) ?? 32;
  let c = code;
  if (c >= 0x61 && c <= 0x7a) c -= 32;          // 小写 → 大写
  if (c < 0x20 || c > 0x5f) c = 0x3f;           // 其余 → '?'
  return TABLE[c - 0x20];
}

/** 一段文字画出来的像素宽度（含字距）。 */
export function textWidth(text, scale = 1, tracking = 1) {
  const n = [...String(text)].length;
  if (n === 0) return 0;
  return (n * 5 + (n - 1) * tracking) * scale;
}

/** 字高（scale=1 时 7px）。 */
export function textHeight(scale = 1) {
  return 7 * scale;
}

/**
 * 把文字画进一张 RGB 缓冲。
 *
 * @param {Uint8Array|Buffer} rgb 目标缓冲（原地改写）
 * @param {number} width 目标宽
 * @param {number} height 目标高
 * @param {string} text
 * @param {number} x
 * @param {number} y
 * @param {{scale?:number, color?:[number,number,number], tracking?:number, bg?:[number,number,number]|null, pad?:number}} [opts]
 */
export function drawText(rgb, width, height, text, x, y, opts = {}) {
  const {
    scale = 1, color = [255, 255, 255], tracking = 1, bg = null, pad = 0, bgAlpha = 0.22,
  } = opts;
  const chars = [...String(text)];
  if (!chars.length) return;

  if (bg) {
    const bx = Math.max(0, x - pad);
    const by = Math.max(0, y - pad);
    const bw = Math.min(width - bx, textWidth(text, scale, tracking) + pad * 2);
    const bh = Math.min(height - by, textHeight(scale) + pad * 2);
    for (let yy = by; yy < by + bh; yy += 1) {
      for (let xx = bx; xx < bx + bw; xx += 1) {
        const p = (yy * width + xx) * 3;
        // 半透明压暗，字才在亮画面上也读得出来
        rgb[p] = (rgb[p] * bgAlpha) | 0;
        rgb[p + 1] = (rgb[p + 1] * bgAlpha) | 0;
        rgb[p + 2] = (rgb[p + 2] * bgAlpha) | 0;
      }
    }
  }

  let cx = x;
  for (const ch of chars) {
    const glyph = glyphOf(ch);
    for (let row = 0; row < 7; row += 1) {
      for (let col = 0; col < 5; col += 1) {
        if (!glyph[row][col]) continue;
        for (let sy = 0; sy < scale; sy += 1) {
          const py = y + row * scale + sy;
          if (py < 0 || py >= height) continue;
          for (let sx = 0; sx < scale; sx += 1) {
            const px = cx + col * scale + sx;
            if (px < 0 || px >= width) continue;
            const p = (py * width + px) * 3;
            rgb[p] = color[0];
            rgb[p + 1] = color[1];
            rgb[p + 2] = color[2];
          }
        }
      }
    }
    cx += (5 + tracking) * scale;
  }
}
